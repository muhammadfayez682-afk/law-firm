// تطبيع النص العربي للبحث المتسامح مع اختلاف صيغ الحروف.
// دالة نقية قابلة لإعادة الاستخدام (عملاء، أطراف، قضايا...).

// التشكيل (الفتحة/الضمة/الكسرة/الشدة/السكون/التنوين...) والتطويل.
const ARABIC_DIACRITICS = /[ً-ْٰـ]/g;

/**
 * يُوحّد النص العربي:
 *  - الألف بكل صيغها (أ إ آ ٱ) → ا
 *  - الياء/الألف المقصورة (ى) → ي
 *  - التاء المربوطة (ة) → ه
 *  - إزالة التشكيل والتطويل (ـ)
 *  - trim + توحيد المسافات المتعددة إلى واحدة
 *  - lowercase (للأسماء اللاتينية المختلطة)
 */
export function normalizeArabic(s: string): string {
  if (!s) return "";
  return s
    .replace(ARABIC_DIACRITICS, "")
    .replace(/[أإآٱ]/g, "ا") // أ إ آ ٱ → ا
    .replace(/ى/g, "ي") // ى → ي
    .replace(/ة/g, "ه") // ة → ه
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
